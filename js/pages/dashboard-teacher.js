    // Global article functions
    window.editTeacherArticle = function(id) {
        const articles = window.db.getArticles();
        const a = articles.find(x => x.id == id);
        if (!a) return;
        document.getElementById('tdArticleId').value = a.id;
        document.getElementById('tdArticleTitle').value = a.title;
        document.getElementById('tdArticleExcerpt').value = a.excerpt;
        document.getElementById('tdArticleContent').value = a.content;
        document.getElementById('tdArticleCategory').value = a.category;
        document.getElementById('tdArticleImage').value = a.image || '';
        document.getElementById('tdArticleModal').classList.add('active');
    };

    window.deleteTeacherArticle = function(id) {
        if (!confirm('هل أنت متأكد من حذف هذا المقال؟')) return;
        window.db.deleteArticle(id);
        renderArticles();
        showToast('تم حذف المقال ✅');
    };

    window.generateTeacherArticleAI = function() {
        const title = document.getElementById('tdArticleTitle').value.trim();
        if (!title) { showToast('أدخل عنوان المقال أولاً', 'error'); return; }
        if (!window.AI_ASSISTANT) { showToast('المساعد الذكي غير متاح', 'error'); return; }
        const category = document.getElementById('tdArticleCategory').value;
        showToast('جاري توليد المقال بالذكاء الاصطناعي... ⏳', 'info');
        AI_ASSISTANT.generateArticle(title, category).then(result => {
            document.getElementById('tdArticleExcerpt').value = result.excerpt.replace(/<[^>]*>/g, '');
            document.getElementById('tdArticleContent').value = result.content;
            showToast('✅ تم توليد المقال بالذكاء الاصطناعي!');
        }).catch(() => {
            showToast('حدث خطأ في التوليد', 'error');
        });
    };

