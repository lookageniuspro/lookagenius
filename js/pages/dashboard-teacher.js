    window.editLesson = function(courseId, lessonId, moduleId) {
        const course = window.db.getCourses().find(c => c.id === courseId);
        if (!course) return;
        let lesson = null;
        if (course.modules && course.modules.length > 0) {
            for (const mod of course.modules) {
                if (mod.lessons) {
                    lesson = mod.lessons.find(l => l.id === lessonId);
                    if (lesson) break;
                }
            }
        }
        if (!lesson && course.lessons) lesson = course.lessons.find(l => l.id === lessonId);
        if (!lesson) return;
        document.getElementById('tdLessonEditId').value = lessonId;
        document.getElementById('tdLessonEditModuleId').value = moduleId || '';
        document.getElementById('tdLessonTitle').value = lesson.title;
        document.getElementById('tdLessonVideo').value = lesson.videoURL || '';
        document.getElementById('tdLessonDuration').value = lesson.duration || '';
        document.getElementById('tdLessonFree').checked = lesson.isFree || false;
        if (moduleId && document.getElementById('tdLessonModuleSelect')) {
            document.getElementById('tdLessonModuleSelect').value = moduleId;
        }
        document.getElementById('tdLessonFormTitle').textContent = 'تعديل الدرس';
    };

