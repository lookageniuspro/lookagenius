    function setupNavigation() {
        document.querySelectorAll('[data-tpage]').forEach(btn => {
            btn.addEventListener('click', () => {
                document.querySelectorAll('[data-tpage]').forEach(b => b.classList.remove('active'));
                btn.classList.add('active');
                document.querySelectorAll('.td-page').forEach(s => s.classList.remove('active'));
                const page = document.getElementById('tdPage-' + btn.dataset.tpage);
                if (page) page.classList.add('active');
                currentPage = btn.dataset.tpage;
                if (currentPage === 'dashboard') renderDashboard();
                if (currentPage === 'courses') renderCourses();
                if (currentPage === 'settlements') renderSettlements();
                if (currentPage === 'financials') renderFinancials();
                if (currentPage === 'articles') renderArticles();
            });
        });
        document.getElementById('tdLogoutBtn').addEventListener('click', () => { if (window.auth) window.auth.logout(); });
    }

